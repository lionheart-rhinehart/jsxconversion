// ============================================================================
//  scripts/gen-design-md.mjs — generate per-brand DESIGN.md (the "how-to-design"
//  CONSTRAINT layer that pairs with the example library, the "show" layer)
// ============================================================================
//  Adopts open-design's verified 9-section schema. The brand DESIGN.md is a
//  GENERATED VIEW, not a source of truth: tokens come from data/brand.<slug>.json
//  (canonical; byte-exact mirror of templates/multi-sport-foundations/_helpers.jsx),
//  the prose from one shared curated block with per-brand substitution. Re-run this
//  after any token change — hand edits are forbidden (each file carries a stamp).
//
//  WHY generated (not hand-written): the project bans bare hex in templates
//  (validate-templates.mjs) precisely because copies drift. A hand-typed DESIGN.md is
//  the same trap. This script is the single owner of all 6 DESIGN.md.
//
//  Run:  node scripts/gen-design-md.mjs
//  Node-only. Reads data/brand.*.json; writes <kitPath>/DESIGN.md per brand.
// ============================================================================

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const DATA_DIR = join(ROOT, "data");

// ── token access: FLAG a missing token, never substitute another brand's value ──
function tok(tags, key, warnings, brand) {
  const v = tags[key];
  if (v == null || v === "") { warnings.push(`${brand}: missing token "${key}" — left as TODO (NOT substituted)`); return null; }
  return v;
}
const orTodo = (v) => v == null ? "_TODO: not tokenized — add to data/brand.<slug>.json_" : v;

// ── the 9 sections (open-design schema). Prose is shared + per-brand substituted. ──
function buildDesignMd(ctx) {
  const { name, slug, primary, primaryDeep, ink950, ink900, surface, fontDisplay, fontBody, fontMono, guarantee, url, isAA } = ctx;
  const stamp = `<!-- GENERATED by scripts/gen-design-md.mjs from data/brand.${slug}.json — do not hand-edit; re-run on token change. -->`;
  const guaranteeBlock = isAA
    ? `Guarantee (state **verbatim**, the operative value that fills creatives):\n> ${orTodo(guarantee)}`
    : `Guarantee (state **verbatim** if used):\n> ${orTodo(guarantee)}`;

  return `${stamp}
# ${name}

## Visual Theme & Atmosphere
Performance-grade and no-nonsense — head-coach-to-parent confidence, not hype. Dark ink fields, one
decisive accent, oversized condensed display type, and real athletes mid-effort. Nothing decorative:
every element earns its place. The squint test rules — one dominant idea per frame.

## Color Palette & Roles
Tokens are canonical in \`data/brand.${slug}.json\` (\`tags\`). Labeled by ROLE (the primary token is
named \`brand_red\` but is the brand's accent at whatever hue — do not call it "red").
- **Primary / accent** — ${orTodo(primary)} (\`brand_red\`): the single decisive accent — bars, eyebrows, CTA, key numerals.
- **Primary, deep** — ${orTodo(primaryDeep)} (\`brand_red_deep\`): pressed/hover and depth under the accent.
- **Ink, deepest** — ${orTodo(ink950)} (\`ink_950\`): the deepest background field.
- **Ink, raised** — ${orTodo(ink900)} (\`ink_900\`): raised panels/cards a step above the base.
- **Surface** — ${orTodo(surface)} (\`white\`): primary text on ink, and light-register backgrounds.
Use ONE accent per frame; never two competing accents. Photo tints are accent at low alpha, not solid fills.

## Typography Rules
- **Display** — ${orTodo(fontDisplay)} (\`font_display\`): condensed, UPPERCASE headlines + giant numerals.
- **Body** — ${orTodo(fontBody)} (\`font_body\`): supporting copy, captions, sub-labels.
- **Metrics / labels** — ${orTodo(fontMono)} (\`font_mono\`): eyebrows, kickers, stats, stamps (letter-spaced, uppercase).
- **Scale / line-height:** _TODO: not tokenized — derive from \`templates/multi-sport-foundations/_helpers.jsx\` usage (display ~80–230px, body ~32–48px, mono ~24–34px)._

## Component Stylings
- **Media** — every creative carries a real image/video via the full-bleed \`MediaSlot\` (cover-fit; focal
  offset/scale/crop supported). No bare type cards.
- **Accent bar** — a solid Primary rule/bar as a hierarchy divider (e.g. a thin underline or a bold block).
- **Eyebrow** — mono, uppercase, letter-spaced; on a chip or inline above the headline.
- **Headline** — Display, uppercase, tight line-height (~0.9), edge-to-edge.
- **Metric chip** — mono/Display numerals on an ink or accent field.

## Layout Principles
- Canvas: **1080×1920 vertical** (9:16) is primary. Generous edge padding (~56–72px).
- Strong top-to-bottom hierarchy; ONE dominant element per frame (number, headline, photo, or chart).
- Full-bleed media behind a legible scrim, OR a clean split (media half / panel half).

## Depth & Elevation
Mostly flat with ONE elevation tier. Lift cards with \`drop-shadow(0 4px 14px rgba(0,0,0,0.55))\`; a
focal glow uses \`drop-shadow(0 0 14px <Primary>)\`. No multi-layer shadow stacks.

## Do's and Don'ts
(Text markers, not dingbats — this brand bans emoji, including in its own docs.)
- **Do** — put **real media** on every creative (image/video/clip).
- **Do** — keep voice **head-coach-to-parent**: declarative, metric-driven, calm authority.
- **Do** — state the guarantee **verbatim** (below) when used.
- **Do** — one accent, one dominant element, generous negative space.
- **Don't** — use **emoji or exclamation points**, or hype adjectives.
- **Don't** — paraphrase the guarantee.
- **Don't** — ship a bare type card with no media; stack two accents; or hardcode hex in templates
  (tokenize via the brand kit — \`validate-templates.mjs\` enforces this).

## Responsive Behavior
- **Primary:** 1080×1920 (9:16) for Reels / Stories / Shorts.
- **Feed variants:** 1:1 (1080×1080) and 4:5 (1080×1350) — _TODO: breakpoints not tokenized; re-flow the
  same hierarchy, keep the dominant element and the accent._

## Agent Prompt Guide
When designing for **${name}**:
- Pull EVERY color/font from the brand kit (\`data/brand.${slug}.json\`) — never hardcode. Primary accent
  = ${orTodo(primary)}; Display ${orTodo(fontDisplay)}, Body ${orTodo(fontBody)}, Metrics ${orTodo(fontMono)}.
- Carry real media on every creative; pull it from the content library, never a placeholder.
- Write head-coach-to-parent: declarative, metric-driven; **no emoji, no exclamation points**.
- ${guaranteeBlock}
${url ? `- Brand handle / URL: ${url}.` : ""}
- One dominant element per frame; pass the squint test. Distinctness comes from STRUCTURE, not font size.
`;
}

// ---------------------------------------------------------------------------
function main() {
  const files = readdirSync(DATA_DIR).filter((f) => /^brand\.[\w-]+\.json$/.test(f)).sort();
  if (!files.length) { process.stderr.write("[gen-design-md] no data/brand.*.json found\n"); process.exit(1); }

  const warnings = [];
  let written = 0;
  for (const f of files) {
    const slug = f.replace(/^brand\./, "").replace(/\.json$/, "");
    const b = JSON.parse(readFileSync(join(DATA_DIR, f), "utf8"));
    const tags = b.tags || {};
    const kitPath = b.kitPath;
    if (!kitPath) { warnings.push(`${slug}: NO kitPath in ${f} — skipped (can't place DESIGN.md)`); continue; }
    const kitAbs = join(ROOT, kitPath);
    if (!existsSync(kitAbs)) { warnings.push(`${slug}: kitPath "${kitPath}" does not exist — skipped`); continue; }

    const ctx = {
      name: tok(tags, "brand_name", warnings, slug) || b.brand || slug,
      slug,
      primary: tok(tags, "brand_red", warnings, slug),
      primaryDeep: tok(tags, "brand_red_deep", warnings, slug),
      ink950: tok(tags, "ink_950", warnings, slug),
      ink900: tok(tags, "ink_900", warnings, slug),
      surface: tok(tags, "white", warnings, slug),
      fontDisplay: tok(tags, "font_display", warnings, slug),
      fontBody: tok(tags, "font_body", warnings, slug),
      fontMono: tok(tags, "font_mono", warnings, slug),
      guarantee: tok(tags, "guarantee", warnings, slug),
      url: tags.url || null,
      isAA: slug === "athletes-acceleration",
    };
    writeFileSync(join(kitAbs, "DESIGN.md"), buildDesignMd(ctx));
    process.stderr.write(`[gen-design-md] wrote ${kitPath}/DESIGN.md (${ctx.name})\n`);
    written++;
  }
  for (const w of warnings) process.stderr.write(`[gen-design-md] FLAG: ${w}\n`);
  process.stderr.write(`[gen-design-md] generated ${written} DESIGN.md from ${files.length} brand kit(s)\n`);
}

main();
