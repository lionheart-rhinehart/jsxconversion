// creative-engine/editor/bundle.mjs
//
// Phase 4.1 — pack the ONE portable editor into a single, embeddable bundle.
//
// WHY a bundle: today the editor mounts as four cooperating files (editor.js +
// montage.mjs + editor.css + apply-overrides.js), and the host page has to (a) <link>
// the CSS, (b) fetch apply-overrides.js as text into window.__CE_APPLY_SRC__ BEFORE
// editor.js runs, and (c) serve all four by relative path. That works on OUR dev host
// (editor-host.html) — but a FOREIGN host on a different origin (the Kraken Next.js
// app) can't be trusted to fetch our peer files by relative path or honor that load
// order. So Phase 4 collapses the four files into ONE self-contained ES module that:
//
//   • carries the editor CSS inside it and injects a <style> on mount (no <link>);
//   • carries the apply-overrides.js SOURCE as a string and sets __CE_APPLY_SRC__
//     itself (no fetch, no load-order trap) — the iframe still gets the SAME source;
//   • inlines montage.mjs (its only import) so there are ZERO peer-file imports.
//
// The result — dist/creative-engine-editor.bundle.js — is the thing Kraken imports:
//   import { mountEditor } from '.../creative-engine-editor.bundle.js'
//   mountEditor({ container, html, permissions: 'view' | 'edit', ... })
//
// CLEAN ROOM: this is a deterministic string concat of our own Phase-2 files. No
// bundler, no framework, zero imports from creative-engine-v1/. Re-run to rebuild.
//
// Usage:  node creative-engine/editor/bundle.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => fs.readFileSync(path.join(__dirname, f), 'utf8');

const css = read('editor.css');
const applySrc = read('apply-overrides.js');
let montage = read('montage.mjs');
let editor = read('editor.js');

// 1) montage.mjs → module-local: drop EVERY leading `export ` so its decls live at the
//    bundle's module scope (that's exactly what editor.js's import expected). Strip ALL
//    of them, incl. `export async function` — leaving the node-only render helpers
//    (buildMontageSource/buildMontageAudio, which dynamic-import node:child_process)
//    EXPORTED would make a browser bundler (Kraken's Next.js webpack/turbopack) try to
//    resolve node builtins for a browser target → build warning/error. They stay as
//    unexported module-local fns: present but never reachable, never re-exported.
//    montage.mjs imports nothing at the top level, so it inlines verbatim otherwise.
montage = montage.replace(/^export\s+/gm, '');

// 2) editor.js → remove the now-satisfied montage import (names are in scope above).
const importLine = "import { clipFrames, montageAt, cycleDurationMs, normalizeMontage, normalizeAudio } from './montage.mjs';";
if (!editor.includes(importLine)) throw new Error('bundle: montage import line not found in editor.js — did its imports change?');
editor = editor.replace(importLine, '// [bundled] montage math inlined above');

// 3) editor.js → call __ceEnsureChrome() as the first thing mountEditor does, so the
//    bundle injects its CSS + sets __CE_APPLY_SRC__ lazily (mount time, never import
//    time — safe under SSR where `document` is undefined at import).
const mountSig = 'export function mountEditor(opts) {';
if (!editor.includes(mountSig)) throw new Error('bundle: mountEditor signature not found in editor.js');
editor = editor.replace(mountSig, mountSig + '\n  __ceEnsureChrome();');

const prelude = `// ───────────────────────────────────────────────────────────────────────────
// creative-engine-editor.bundle.js — GENERATED by bundle.mjs. Do not edit by hand.
// One self-contained ES module: the Phase-2 portable editor + its CSS + the shared
// apply-overrides source + the montage math, in a single import. Rebuild:
//     node creative-engine/editor/bundle.mjs
// ───────────────────────────────────────────────────────────────────────────
const __CE_CSS__ = ${JSON.stringify(css)};
const __CE_APPLY_SRC__ = ${JSON.stringify(applySrc)};

// Lazy, idempotent host setup — runs on the FIRST mountEditor() call, never at import.
function __ceEnsureChrome() {
  if (typeof document !== 'undefined' && !document.getElementById('ce-editor-css')) {
    const s = document.createElement('style');
    s.id = 'ce-editor-css';
    s.textContent = __CE_CSS__;
    document.head.appendChild(s);
  }
  if (typeof window !== 'undefined' && !window.__CE_APPLY_SRC__) {
    // the SAME source editor.js injects into the design iframe (so preview == render).
    window.__CE_APPLY_SRC__ = __CE_APPLY_SRC__;
  }
}

`;

const epilogue = `

// Convenience global for non-module hosts (the Kraken mount can also do
// <script type="module"> import + window.CreativeEngineEditor).
if (typeof window !== 'undefined') {
  window.CreativeEngineEditor = Object.assign(window.CreativeEngineEditor || {}, { mountEditor });
}
`;

const out = prelude
  + '// ── inlined montage.mjs (pure timeline math; export keyword stripped) ──\n'
  + montage + '\n\n'
  + '// ── inlined editor.js (montage import removed; ensureChrome injected) ──\n'
  + editor
  + epilogue;

const distDir = path.join(__dirname, 'dist');
fs.mkdirSync(distDir, { recursive: true });
const bundlePath = path.join(distDir, 'creative-engine-editor.bundle.js');
fs.writeFileSync(bundlePath, out);

const kb = (out.length / 1024).toFixed(1);
console.log(`bundle → ${path.relative(path.resolve(__dirname, '..', '..'), bundlePath)}  (${kb} KB)`);

// sanity: no leftover peer-file import survived the inline (the whole point of 4.1).
const leftover = out.match(/^\s*import\s.+from\s+['"]\.[^'"]+['"]/gm);
if (leftover) {
  console.error('BUNDLE NOT SELF-CONTAINED — leftover relative import(s):\n' + leftover.join('\n'));
  process.exit(1);
}
console.log('self-contained: 0 relative peer imports remain.');
